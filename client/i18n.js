export const lang = () => (document.documentElement.dataset.lang === 'de' ? 'de' : 'en');
export const has = (key) => key in DICT.en;

// t('goal', { total: 42, goal: 63 }). An unknown key comes back as itself (e.g. a raw error message).
export function t(key, vars = {}) {
  const s = DICT[lang()][key] ?? DICT.en[key] ?? String(key);
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
export const sats = (n) => t(n === 1 ? 'sat' : 'sats', { n });

// Static text: <b data-t="key">…</b> (our own strings, so innerHTML is safe for the <em>s).
export function translatePage() {
  document.querySelectorAll('[data-t]').forEach((el) => (el.innerHTML = t(el.dataset.t)));
}
export function onLang(fn) {
  addEventListener('nutpub-lang', () => { translatePage(); fn?.(); });
  translatePage();
}
